const isLoopbackHost = (host) => {
  const value = host.toLowerCase();
  return (
    value === "localhost" ||
    value === "::1" ||
    value === "[::1]" ||
    (net.isIPv4(value) && Number(value.split(".")[0]) === 127)
  );
};

